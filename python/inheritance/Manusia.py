class Manusia:
    def __init__(self):
        self.nama = ""
        self.alamat = ""
        self.no_ktp = ""
        self.no_telepon = ""

    def set_nama(self, nama):
        self.nama = nama
    
    def get_nama(self):
        return self.nama
    
    def set_alamat(self, alamat):
        self.alamat = alamat
    
    def get_alamat(self):
        return self.alamat
    
    def set_no_ktp(self, no_ktp):
        self.no_ktp = no_ktp
    
    def get_no_ktp(self):
        return self.no_ktp
    
    def set_no_telepon(self, no_telepon):
        self.no_telepon = no_telepon
    
    def get_no_telepon(self):
        return self.no_telepon